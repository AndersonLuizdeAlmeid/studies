/*
 1. 🚀 Big O Notation
Big O notation (like O(n)) doesn't tell you the exact time an algorithm will take (e.g., 0.02 seconds). Instead, it describes how the runtime (or memory usage) scales as the input size (n) grows.

n = The size of the input (e.g., the number of elements in an array, the number of nodes in a linked list).

Time Complexity = How does the number of operations grow as n grows?

Space Complexity = How does the amount of memory used grow as n grows?

When we analyze, we always consider the worst-case scenario.
 */