/*
 
    OOP is a programming approach that helps solve real-life problems by representing real objects in code.

    Principles of OOP are consist across all programming languages, meaning what you learn can be applied in languages like C#, Java, Python, etc.
    
    Classes -> Blueprints that describe what an entity in a program should have(proprerties) and what it should do(behaviors/methods).
    Objects -> Instances of classes that hold specific data and can perform actions defined by their class.

    A Class can be a person that has properties like Name, Age, and behaviors like Speak() and Walk().
    An object would be a specific person, like Me, who has the name "John" and age 30, can speak and walk, based on the Person class blueprint.
 */